def chip(s, x, y, txt, color, bg, size=12, w=None, h=0.34):
    w = w or (0.13 * len(txt) * size / 12 + 0.3)
    b = box(s, x, y, w, h, bg, radius=0.5, line=color, line_w=1.0)
    text(s, x, y, w, h, txt, size=size, color=color, bold=True, align=PP_ALIGN.CENTER, anchor=MSO_ANCHOR.MIDDLE)
    return w


def _ln(side, w_pt, color="1F2A37"):
    ln = etree.Element(qn("a:ln" + side))
    if w_pt:
        ln.set("w", str(int(w_pt * 12700))); sf = etree.SubElement(ln, qn("a:solidFill"))
        etree.SubElement(sf, qn("a:srgbClr")).set("val", color)
    else:
        etree.SubElement(ln, qn("a:noFill"))
    return ln


def table(slide, rows, x, y, col_w, row_h=0.42, size=14, header=1, align=None, bold_rows=(), colors=None):
    """Booktabs-style native table (rules only)."""
    nr, nc = len(rows), len(rows[0]); align = align or ("l" + "c" * (nc - 1)); colors = colors or {}
    gf = slide.shapes.add_table(nr, nc, Inches(x), Inches(y), Inches(sum(col_w)), Inches(row_h * nr))
    tbl = gf.table; tbl.first_row = False; tbl.horz_banding = False
    tblPr = tbl._tbl.tblPr; sid = tblPr.find(qn("a:tableStyleId"))
    if sid is None:
        sid = etree.SubElement(tblPr, qn("a:tableStyleId"))
    sid.text = NO_STYLE
    for i, cw in enumerate(col_w):
        tbl.columns[i].width = Inches(cw)
    for r in range(nr):
        tbl.rows[r].height = Inches(row_h)
        for c in range(nc):
            cell = tbl.cell(r, c); cell.vertical_anchor = MSO_ANCHOR.MIDDLE
            cell.margin_left = cell.margin_right = Inches(0.06); cell.margin_top = cell.margin_bottom = Inches(0.03)
            tf = cell.text_frame; tf.word_wrap = True
            p = tf.paragraphs[0]; p.alignment = {"l": PP_ALIGN.LEFT, "c": PP_ALIGN.CENTER}[align[c]]
            run = p.add_run(); run.text = rows[r][c]; f = run.font; f.name = SANS; f.size = Pt(size)
            f.bold = r < header or r in bold_rows; f.color.rgb = colors.get((r, c), INK); ea(f)
            cell.fill.solid(); cell.fill.fore_color.rgb = WHITE
            tcPr = cell._tc.get_or_add_tcPr()
            top = 1.25 if r == 0 else None
            bottom = 1.25 if r == nr - 1 else (0.75 if r == header - 1 else None)
            for i, (side, wpt) in enumerate((("L", None), ("R", None), ("T", top), ("B", bottom))):
                tcPr.insert(i, _ln(side, wpt))
    return gf


