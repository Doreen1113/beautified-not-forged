def picture(slide, path, x, y, w, h, align="center", valign="top"):
    """Fit an image into the (x, y, w, h) box, keeping its aspect ratio."""
    iw, ih = Image.open(path).size; r = iw / ih
    pw, ph = (w, w / r) if w / r <= h else (h * r, h)
    px = x + (w - pw) / 2 if align == "center" else (x + w - pw if align == "right" else x)
    py = y if valign == "top" else y + (h - ph) / 2
    slide.shapes.add_picture(str(path), Inches(px), Inches(py), Inches(pw), Inches(ph))
    return px, py, pw, ph


