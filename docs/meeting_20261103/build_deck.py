def heat_matrix(s, x, y, cell, counts, labels):
    """Confusion matrix, rows = true class, columns = predicted; cell colour = row share; text = share and count."""
    n = len(labels)
    text(s, x + 1.25, y - 0.34, cell * n, 0.3, "predicted", size=12, color=MUTED, italic=True, align=PP_ALIGN.CENTER)
    for j, lab in enumerate(labels):
        text(s, x + 1.25 + j * cell, y, cell, 0.3, lab, size=13, bold=True, align=PP_ALIGN.CENTER)
    for i, lab in enumerate(labels):
        tot = sum(counts[i]); yy = y + 0.35 + i * cell
        text(s, x, yy, 1.15, cell, lab, size=13, bold=True, align=PP_ALIGN.RIGHT, anchor=MSO_ANCHOR.MIDDLE)
        for j in range(n):
            v = counts[i][j] / tot; a = 0.12 + 0.88 * v
            col = RGBColor(int(0xF4 + (0x0F - 0xF4) * a), int(0xF6 + (0x4D - 0xF6) * a), int(0xF9 + (0x92 - 0xF9) * a))
            box(s, x + 1.25 + j * cell, yy, cell - 0.04, cell - 0.04, col, radius=0.04)
            fg = WHITE if v > 0.45 else INK
            text(s, x + 1.25 + j * cell, yy + 0.08, cell - 0.04, cell - 0.16,
                 [[(f"{100 * v:.1f}%", {"bold": True, "size": 17, "color": fg})], [(f"({counts[i][j]:,})", {"size": 11, "color": fg})]],
                 align=PP_ALIGN.CENTER, anchor=MSO_ANCHOR.MIDDLE)


def bar_chart(s, x, y, w, h, cats, vals, colors, size=12):
    cd = CategoryChartData(); cd.categories = cats; cd.add_series("share", vals)
    gf = s.shapes.add_chart(XL_CHART_TYPE.BAR_CLUSTERED, Inches(x), Inches(y), Inches(w), Inches(h), cd)
    ch = gf.chart; ch.has_legend = False; ch.has_title = False
    pl = ch.plots[0]; pl.gap_width = 45; pl.has_data_labels = True
    dl = pl.data_labels; dl.number_format = '0.0'; dl.number_format_is_linked = False
    dl.position = XL_LABEL_POSITION.OUTSIDE_END; dl.font.size = Pt(size); dl.font.color.rgb = INK
    va = ch.value_axis; va.maximum_scale = 112; va.minimum_scale = 0; va.has_major_gridlines = False; va.visible = False
    ca = ch.category_axis; ca.tick_labels.font.size = Pt(size); ca.tick_labels.font.color.rgb = INK; ca.reverse_order = True
    ca.format.line.color.rgb = RGBColor(0xC8, 0xCD, 0xD3)
    for i, c in enumerate(colors):
        pt = pl.series[0].points[i]; pt.format.fill.solid(); pt.format.fill.fore_color.rgb = c
    return gf


def stacked_chart(s, x, y, w, h, cats, series, colors, size=12):
    cd = CategoryChartData(); cd.categories = cats
    for name, vals in series:
        cd.add_series(name, vals)
    gf = s.shapes.add_chart(XL_CHART_TYPE.BAR_STACKED_100, Inches(x), Inches(y), Inches(w), Inches(h), cd)
    ch = gf.chart; ch.has_title = False; ch.has_legend = True; ch.legend.position = XL_LEGEND_POSITION.TOP
    ch.legend.include_in_layout = False; ch.legend.font.size = Pt(size)
    pl = ch.plots[0]; pl.gap_width = 40; pl.overlap = 100; pl.has_data_labels = True
    dl = pl.data_labels; dl.number_format = '0'; dl.number_format_is_linked = False; dl.font.size = Pt(size)
    dl.font.color.rgb = WHITE; dl.position = XL_LABEL_POSITION.CENTER
    ch.value_axis.visible = False; ch.value_axis.has_major_gridlines = False
    ca = ch.category_axis; ca.tick_labels.font.size = Pt(size); ca.reverse_order = True
    for k, c in enumerate(colors):
        sr = pl.series[k]; sr.format.fill.solid(); sr.format.fill.fore_color.rgb = c
    return gf


