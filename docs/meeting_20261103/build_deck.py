def chips_column(s, x0, y0, x1, items, color, bg, size=12, gap=0.1, row=0.44):
    x, y = x0, y0
    for r in items:
        w = (0.095 * len(r) + 0.32) if not ZH else (0.2 * len(r) + 0.3)
        if x + w > x1:
            x, y = x0, y + row
        chip(s, x, y, r, color, bg, size=size, w=w); x += w + gap
    return y + row


