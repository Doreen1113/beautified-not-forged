def tex(s):
    s = s.replace("%", r"\%").replace("_", r"\_").replace("->", r"$\rightarrow$").replace("<=", r"$\le$").replace(">=", r"$\ge$")
    s = re.sub(r"(?<![\d.])-(?=\d)", r"$-$", s)
    return s


def md_tables(path):
    """All pipe tables of a markdown file as lists of rows (header first), in order, with the text line preceding each."""
    lines = path.read_text(encoding="utf-8").splitlines()
    tabs, cur, pre = [], [], ""
    for i, ln in enumerate(lines):
        if ln.startswith("|"):
            cells = [c.strip() for c in ln.strip().strip("|").split("|")]
            if all(set(c) <= set("-: ") for c in cells):
                continue
            cur.append(cells)
        else:
            if cur:
                tabs.append((pre, cur)); cur = []
            if ln.strip():
                pre = ln.strip()
    if cur:
        tabs.append((pre, cur))
    return tabs


def write(name, header, rows, spec, src, name_col=True, tr=None):
    out = [f"% generated by make_tables_v8_supp.py from {src}", r"\begin{tabular}{" + spec + "}", r"\toprule",
           " & ".join(header) + r" \\", r"\midrule"]
    for r in rows:
        cells = list(r)
        if name_col:
            cells[0] = NAME.get(cells[0], tex(cells[0]))
        else:
            cells[0] = tex(cells[0])
        cells = [cells[0]] + [tex(c) if tr is None else tr(c) for c in cells[1:]]
        out.append(" & ".join(cells) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}", ""]
    (OUT / name).write_text("\n".join(out), encoding="utf-8")
    print("wrote", name, len(rows), "rows")


