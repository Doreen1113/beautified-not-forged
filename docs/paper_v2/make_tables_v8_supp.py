def bars():
    txt = (RU / "READOUT46.md").read_text(encoding="utf-8")
    rows = []
    for m in re.finditer(r"^## (\S+) \((.*)\)\n\nbars: (.*)$", txt, re.M):
        key, desc, b = m.groups()
        if "not trained" in desc or not b.strip():
            continue
        d = dict(kv.rsplit("=", 1) for kv in b.split(", "))
        seed = "1" if key.endswith("s20260929") else "2"
        flags = [d["1_facelocal_fa<=15"], d["2_bil15_21_fa<=15_and_S90<=15"], d["3_as_written"], d["3prime"],
                 d["4_untreated_video_not_lower_than_binary_by>0.010"], d["5_cdfb_auc_b>=main"], d["6_df40_reenactment_not_lower_by>0.030"]]
        n = sum(f == "True" for f in flags[:2] + flags[3:])
        rows.append([tex(key.split("_")[0]) + " (" + tex(desc) + ")", seed] + [r"\checkmark" if f == "True" else "--" for f in flags] + [f"{n}/6"])
    hdr = ["Arm (READOUT46 key)", "seed", "1 face-local FA", "2 whole-crop and S-90", "3 as written", "3$'$ relaxed",
           "4 untreated video", "5 Celeb-DF-B AUC", "6 DF40 reenactment", "passed"]
    write("tab_v8_bars.tex", hdr, rows, "@{}l c ccccccc c@{}", "retouch_unified_20260929/READOUT46.md (bars lines)", name_col=False)


